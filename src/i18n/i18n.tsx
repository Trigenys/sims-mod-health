export type TranslationKey = keyof typeof fr;
export type Vars = Record<string, string | number>;
export type TranslationFn = (key: TranslationKey, vars?: Vars) => string;

function interpolate(value: string, vars?: Vars) {
  if (!vars) return value;
  return Object.entries(vars).reduce(
    (current, [key, replacement]) =>
      current.replaceAll("{{" + key + "}}", String(replacement)),
    value
  );
}

export function translate(locale: Locale, key: TranslationKey, vars?: Vars) {
  const value = locale === "fr" ? fr[key] : key;
  return interpolate(value, vars);
}

export function translateKnown(locale: Locale, value: string) {
  if (locale !== "fr") return value;
  return Object.prototype.hasOwnProperty.call(fr, value)
    ? fr[value as TranslationKey]
    : value;
}

export function resolveLocale({
  stored,
  system
}: {
  stored?: string | null;
  system?: string | null;
}): Locale {
  if (stored === "fr" || stored === "en") return stored;
  return system?.toLocaleLowerCase().startsWith("fr") ? "fr" : "en";
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, vars?: Vars) => string;
  tx: (value: string) => string;
};

const defaultValue: I18nValue = {
  locale: "en",
  setLocale: () => undefined,
  t: (key, vars) => interpolate(key, vars),
  tx: (value) => value
};

const I18nContext = createContext<I18nValue>(defaultValue);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    resolveLocale({
      stored: window.localStorage.getItem(STORAGE_KEY),
      system: window.navigator.language
    })
  );

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale,
      t: (key, vars) => translate(locale, key, vars),
      tx: (text) => translateKnown(locale, text)
    }),
    [locale, setLocale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

